// Add the relevant example only when a Korean hope/request marker is present.
// This selects examples; it never edits transcript text or makes another API call.
pub(super) fn with_relevant_examples(prompt: String, style: &str, raw: &str) -> String {
    if style != "structured" || !raw.contains("좋겠") || !prompt.contains(STRUCTURED_EXAMPLES) {
        return prompt;
    }
    let examples = STRUCTURED_EXAMPLES.replacen(
        "입력: 표본은 8개 아니 11개예요",
        &format!("{}입력: 표본은 8개 아니 11개예요", HOPE_EXAMPLE),
        1,
    );
    prompt.replacen(STRUCTURED_EXAMPLES, &examples, 1)
}

const HOPE_EXAMPLE: &str = r###"입력: 검색 화면에 필터를 넣어줘 즐겨찾기도 할 수 있으면 좋겠어 추천 알림은 꺼줘 키보드 단축키는 그대로 두고
출력:
- 검색 화면에 필터를 넣어줘.
- 즐겨찾기도 할 수 있으면 좋겠어.
- 추천 알림은 꺼줘.
- 키보드 단축키는 그대로 둬.

"###;

#[cfg(test)]
mod example_selection_tests {
    use super::*;
    #[test]
    fn hope_example_is_scoped_to_matching_structured_transcripts() {
        let base = STRUCTURED_EXAMPLES.to_string();
        assert_eq!(
            with_relevant_examples(
                base.clone(),
                "structured",
                "자료는 가영이 맡고 검토는 도윤이 맡아요"
            ),
            base
        );
        assert!(with_relevant_examples(
            base.clone(),
            "structured",
            "여러 개를 받을 수 있으면 좋겠어"
        )
        .contains(HOPE_EXAMPLE));
        assert!(with_relevant_examples(
            base.clone(),
            "structured",
            "여러 개를 받을 수 있으면 좋겠어요"
        )
        .contains(HOPE_EXAMPLE));
        assert_eq!(
            with_relevant_examples(base.clone(), "clean", "되면 좋겠어"),
            base
        );
        assert_eq!(
            with_relevant_examples(
                "selected text operation".into(),
                "structured",
                "되면 좋겠어"
            ),
            "selected text operation"
        );
    }
}
